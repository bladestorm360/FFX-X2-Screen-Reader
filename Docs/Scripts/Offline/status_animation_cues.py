"""Qualify six stack-buff creation cues from retained, approved DLL copies.

No game access/execution. Exact code operands are rebased using PE relocations;
the target-height query occurs once as EgoTask creates each target's effect.
"""

# Game-source inputs/exports live outside every Git tree.
from pathlib import Path as _EvidencePath
import sys as _evidence_sys
_evidence_repo = next(p for p in _EvidencePath(__file__).resolve().parents
                      if (p / "Docs/Scripts/Offline/evidence_paths.py").is_file())
_evidence_sys.path.insert(0, str(_evidence_repo / "Docs/Scripts/Offline"))
from evidence_paths import evidence_path, evidence_relative, write_replay_adapter

from pathlib import Path
from datetime import datetime, timezone
import json
import re
import pefile
import capstone

ROOT = Path(__file__).resolve().parents[3]
SOURCE = evidence_path(ROOT / 'Docs/Scripts/Offline/output/status_animations_20261009_171247_874998')
ANALYSIS = evidence_path(ROOT / 'Docs/Scripts/Ghidra/output/FFX/status_animations_20261009_171247_874998')
manifest = json.loads((SOURCE / 'manifest.json').read_text())
rows = []
for number, buff in [(3,0),(6,1),(4,2),(5,3),(7,4),(8,5)]:
    name = f'magic_{number:04d}.dll'
    pe = pefile.PE(str(SOURCE / name)); base = pe.OPTIONAL_HEADER.ImageBase
    functions = re.split(r'// Function: ', (ANALYSIS / (name+'.txt')).read_text())
    creation = next(f for f in functions if '+ 0x3ec' in f)
    setup = next(f for f in functions if '+ 0x368' in f and re.search(r'DAT_[0-9a-f]+ = param_1;', f))
    api = int(re.findall(r'DAT_([0-9a-f]+) \+ 0x3ec', creation)[0],16)-base
    owner = int(re.findall(r'DAT_([0-9a-f]+) = param_1', setup)[0],16)-base
    start = int(creation.split()[0].removeprefix('FUN_'),16)-base
    dis = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    instructions = list(dis.disasm(pe.get_data(start,0x500),base+start))
    loads = [i for i,x in enumerate(instructions) if x.mnemonic=='mov' and '0x3ec' in x.op_str]
    assert len(loads)==1
    at = loads[0]; call = instructions[at+1]
    assert call.mnemonic=='call' and call.op_str=='eax'
    window = instructions[at-12].address-base
    cue = call.address+call.size-base
    code = bytearray(pe.get_data(window,cue-window))
    relocs = sorted(e.rva-window for block in pe.DIRECTORY_ENTRY_BASERELOC for e in block.entries
                    if e.type==3 and window<=e.rva and e.rva+4<=cue)
    for pos in relocs:
        code[pos:pos+4] = (int.from_bytes(code[pos:pos+4],'little')-base).to_bytes(4,'little')
    assert len(code)<=96 and len(relocs)<=16
    entry = next(m for m in manifest['modules'] if m['name']==name)
    rows.append(dict(name=name,sha256=entry['sha256'],buff=buff,owner=owner,api=api,
                     size=pe.OPTIONAL_HEADER.SizeOfImage,stamp=pe.FILE_HEADER.TimeDateStamp,
                     window=window,cue=cue,relocs=relocs,code=list(code)))
out = evidence_path(ROOT/'Docs/Scripts/Offline/output')/('status_cues_'+datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S_%f'))
out.mkdir(); (out/'manifest.json').write_text(json.dumps(rows,indent=2)+'\n')
header = ['// Generated by Docs/Scripts/Offline/status_animation_cues.py; retained DLL evidence.',
          '#pragma once','#include <array>','namespace ffx {',
          'struct StatusAnimationLayout { unsigned buff,owner,api,size,stamp,window,cue,length,relocationCount; std::array<uint8_t,96> code; std::array<unsigned,16> relocations; };',
          'inline constexpr StatusAnimationLayout statusAnimationLayouts[]={']
for row in rows:
    fields=','.join(hex(row[k]) for k in ['buff','owner','api','size','stamp','window','cue'])
    header += ['    // '+row['name']+' SHA256 '+row['sha256'],
               '    {'+fields+','+str(len(row['code']))+','+str(len(row['relocs']))+',{'+','.join(map(str,row['code']))+'},{'+','.join(map(str,row['relocs']))+'}},']
header += ['};','}']
(ROOT/'src/native/status_animation_data.hpp').write_text('\n'.join(header)+'\n')
print('PASS: six exact per-target creation cues, relocation-aware code and owner/API globals. Evidence:',out)
