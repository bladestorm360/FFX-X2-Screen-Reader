"""Compile visually verified airship texture labels; no installed reads/runtime OCR."""

# Game-source inputs/exports live outside every Git tree.
from pathlib import Path as _EvidencePath
import sys as _evidence_sys
_evidence_repo = next(p for p in _EvidencePath(__file__).resolve().parents
                      if (p / "Docs/Scripts/Offline/evidence_paths.py").is_file())
_evidence_sys.path.insert(0, str(_evidence_repo / "Docs/Scripts/Offline"))
from evidence_paths import evidence_path, evidence_relative, write_replay_adapter

from pathlib import Path
import json
import hashlib

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'src/native/airship_destinations_labels.json'
catalog = json.loads(SOURCE.read_text(encoding='utf-8'))
maps = catalog['labels_by_map']
assert set(maps) == {str(i) for i in (*range(21, 27), 28, 29, 30)}
for labels in maps.values():
    assert len(labels) == 27 and labels[0] == '' and all(isinstance(s, str) and s for s in labels[1:])
    assert all(len(s) < 128 for s in labels)
lines = ['#pragma once', '// Generated by build_airship_labels_20261019.py; source JSON links original image evidence.',
         '// Native 6403C0 map substitution selects locale; unknown language IDs use map21 as the original does.',
         'namespace ffx::airshipLabels {']
for key, labels in sorted(maps.items(), key=lambda pair: int(pair[0])):
    lines.append(f'inline constexpr const wchar_t* map{key}[27]={{')
    lines.extend('L' + json.dumps(s, ensure_ascii=True) + ',' for s in labels)
    lines.append('};')
lines += ['inline const wchar_t* label(unsigned language,unsigned id) {', '    if(id>26) return nullptr;',
          '    switch(language) {']
for language, graphic in catalog['native_map_by_language'].items():
    graphic = 22 if graphic == 27 else graphic # All nonblank decoded images22/27 are byte-identical.
    lines.append(f'    case {language}:return map{graphic}[id];')
lines += ['    default:return map21[id];', '    }', '}']
choices = catalog['confirmation_by_map']
assert set(choices) == {str(i) for i in range(21, 31)}
for graphic, labels in choices.items():
    assert len(labels) == 2 and all(isinstance(s, str) and 0 < len(s) < 16 for s in labels)
    lines.append(f'inline constexpr const wchar_t* confirmation{graphic}[2]={{' +
                 ','.join('L' + json.dumps(s, ensure_ascii=True) for s in labels) + '};')
lines += ['inline const wchar_t* confirmation(unsigned language,unsigned option) {',
          '    if(option>1) return nullptr;', '    switch(language) {']
for language, graphic in catalog['native_map_by_language'].items():
    lines.append(f'    case {language}:return confirmation{graphic}[option];')
lines += ['    default:return confirmation21[option];', '    }', '}', '}']
(ROOT/'src/native/airship_destinations_data.hpp').write_bytes(('\r\n'.join(lines)+'\r\n').encode('ascii'))
proof = {'catalog_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
         'confirmation_image_sets': len(choices), 'confirmation_options': 2,
         'label_sets': len(maps), 'labels_per_set': 27, 'maximum_length': max(len(s) for v in maps.values() for s in v),
         'runtime_scope': 'only accepted shown selected row or highlighted confirmation choice; no hidden list/unlock data',
         'native_locale_source': 'FUN_006403c0, complete346-byte native graphics-map loader',
         'map27': 'all26 nonblank decoded pixel buffers identical to map22; blank image dimensions differ'}
out=evidence_path(ROOT/'Docs/Scripts/Offline/output/airship_assets_20261019/label-proof.json')
out.write_text(json.dumps(proof,indent=2)+'\n',encoding='utf-8')
print(f'PASS: {len(maps)} verified label sets, 26 nonblank IDs each, bounded ASCII-escaped native catalog.')
