const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../Frida/FFX/sphere_sections.js'),'utf8'),context);
const meta=[{section:0,depth:0},{section:0,depth:1},{section:0,depth:2},{section:1,depth:0},{section:0,depth:2}];
const grid={nodes:meta.map(()=>({valid:true})),links:[{a:0,b:1,travelled:0},{a:1,b:2,travelled:0},{a:2,b:3,travelled:0},{a:1,b:4,travelled:0}]};
assert.deepEqual(Array.from(context.sectionChoices(meta,grid.links,1,true)),[2,4]);
assert.deepEqual(Array.from(context.sectionChoices(meta,grid.links,4,false)),[1]);
assert.deepEqual(Array.from(context.sectionChoices(meta,grid.links,4,true)),[]);
assert.deepEqual(Array.from(context.sectionChoices(meta,grid.links,0,false)),[]);
grid.nodes[2]={valid:true,locked:true,sphere:81};
assert.equal(context.nearestSection(grid,meta,0,1,0,{}),null);
assert.deepEqual(Array.from(context.nearestSection(grid,meta,0,1,0,{81:1})),[0,1,2,3]);
grid.nodes[1]={valid:true,locked:true,sphere:81};
assert.equal(context.nearestSection(grid,meta,0,1,0,{81:1}),null);
assert.deepEqual(Array.from(context.nearestSection(grid,meta,0,1,0,{81:2})),[0,1,2,3]);
grid.links.push({a:0,b:4,travelled:1},{a:4,b:3,travelled:1});
assert.deepEqual(Array.from(context.nearestSection(grid,meta,0,1,0,{})),[0,4,3]);
const gear=context.visibleGear([5,255,0,0],2,id=>'Strength +5%');
assert.deepEqual(Array.from(gear.names),['Strength +5%']); assert.equal(gear.empty,1);
const stats={nodes:[{valid:true,flags:1,activated:1},{valid:true,flags:1,activated:0},{valid:true,flags:2,activated:0}],links:[{a:0,b:1},{a:1,b:2}]};
assert.deepEqual(Array.from(context.statGoals(stats,0,0)),[-1,0,-1]);
assert.deepEqual(Array.from(context.genericPathDepth(stats,0)),[0,1,2]);
const real=JSON.parse(fs.readFileSync(path.join(__dirname,'output/sphere_sections_20261005_145728_598168/sections.json')));
assert.equal(real.sites.length,860); assert.equal(real.edges.length,881);
real.starts.forEach((at,section)=> {assert.equal(real.sites[at].section,section);assert.equal(real.sites[at].depth,0);});
console.log('PASS: offline section branches/endpoints, nearest entry, cumulative owned-key limits, alternate open route and visible equipment names.');
