"""Generate stable exit identities and conservative native area-name choices.

Area selectors are collision/ATEL state, NOT entrance IDs (native 870E90,
83D7A0). Never select area_indices[spawn]. Names remain localized native text.
"""
from pathlib import Path
import json
import re
import sys
from field_text import TextEvidence

ROOT=Path(__file__).resolve().parents[3]
EVIDENCE=Path(__file__).parent/'output/FFX/20261003_audit'

def generate(source,report):
    report=Path(report)
    if report.exists(): raise ValueError('Fresh report path required')
    data=json.loads(Path(source).read_text(encoding='utf8'))
    maps=json.loads((EVIDENCE/'maps_v3.json').read_text(encoding='utf8'))
    areas={int(k):sorted(set(v)-{0}) for k,v in maps['room_areas'].items()}
    text=TextEvidence(EVIDENCE/'text')
    rows=[]
    totals={'variants':data['variants'],'exits':len(data['exits']), 'previous_missing_room':0,
            'previous_missing_area':0,'resolved_names':0,'unknown_names':0,'numbered':0}
    for entry in sorted(data['exits'],key=lambda e:(e['checksum'],e['script'],e['worker'])):
        previous=entry['previousRoom']
        totals['previous_missing_room']+=previous<0
        totals['previous_missing_area']+=previous>=0 and len(areas.get(previous,[]))!=1
        dest=entry['destinations']
        # All graph outcomes must have native room data; an unknown branch
        # cannot be represented as a single known destination.
        known=not entry['incomplete'] and bool(dest) and all(isinstance(d['room'],int) and d['room']>=0 and areas.get(d['room']) for d in dest)
        ids=sorted({a for d in dest for a in areas.get(d['room'],[])}) if known else []
        # This exact trigger remains on the Winno deck while it starts the
        # Jecht challenge. Its later room191 is the memory/flashback stage,
        # not the immediate player destination. Original w34 -> w21e11 ->
        # w22e16 control flow is retained in the October14 Jecht evidence.
        if entry['script']=='swin0200' and entry['checksum']==0x273a7d2b and entry['worker']==34:
            ids=[91]
            entry['context_correction']='Winno deck challenge trigger; subsequent flashback room191'
        entry['areas']=ids
        entry['names']=[text.macro(11,a) for a in ids]
        entry['label_rule']='all native alternatives' if len(ids)>1 else 'native destination' if ids else 'authored label plus stable number'
        totals['resolved_names']+=bool(ids)
        totals['unknown_names']+=not ids
        totals['numbered']+=entry['total']>1 or not ids
        # The largest area set is bounded offline. No dynamic runtime graph
        # walking or localization cache is needed for an authored exit.
        if len(ids)>64: raise ValueError('Unbounded native name alternatives')
        rows.append('    {%s, 0x%x, %d, %d, %d, {%s}},' % (json.dumps(entry['script']),entry['checksum'],entry['worker'],entry['number'],entry['total'],','.join(map(str,ids))))
    directory=ROOT/'src/native'
    includes=[]
    for part,start in enumerate(range(0,len(rows),350)):
        name=f'exit_destinations_{part}.inc'
        (directory/name).write_text('\n'.join(rows[start:start+350])+'\n',encoding='utf8')
        includes.append(f'#include "{name}"')
    (directory/'exit_destinations_data.hpp').write_text('// Generated by generate_exit_destinations.py; names remain native.\n#pragma once\n#include <array>\nnamespace ffx {\nstruct ExitDestination { const char* script; unsigned checksum,worker,number,total; std::array<unsigned,64> areas; };\ninline const ExitDestination exitDestinations[]={\n'+'\n'.join(includes)+'\n};\n}\n',encoding='utf8')
    data['summary']=totals
    report.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print(json.dumps(totals))
    for e in data['exits']:
        if e['script'] in ('cdsp0000','cdsp0100','cdsp0700'):
            print(e['script'],e['worker'],e['destinations'],e['names'])

if __name__=='__main__': generate(sys.argv[1],sys.argv[2])
