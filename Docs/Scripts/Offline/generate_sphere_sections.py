"""Generate bounded standard-grid metadata from preserved, attributed records."""
from pathlib import Path
from collections import deque, Counter
import json
import struct

root = Path(__file__).resolve().parents[3]
source = Path(__file__).parent / 'output/sphere_sections_20261005_145728_598168'
data = json.loads((source / 'components.json').read_text())
reference = Path(__file__).parent / 'output/reader_reference_20261003_235502/block_00c0a000.bin'
raw = reference.read_bytes()
starts = list(struct.unpack_from('<7H', raw, 0xc86c10-0xc0a000))
assert starts == [0,341,540,637,56,224,448]
nodes,edges = data['nodes'],data['edges']
assert len(nodes)==860 and len(edges)==881
adj=[[] for _ in nodes]
for a,b in edges: adj[a].append(b); adj[b].append(a)
owner=[-1]*len(nodes)
for section,start in enumerate(starts):
    group=next(g for g in data['groups'] if start in g)
    for node in group:
        assert owner[node] == -1
        owner[node]=section
# Include an optional locked/stat branch only when its entire component has
# exactly one verified section as its boundary. Shared connectors remain -1.
seen=set()
for node in range(len(nodes)):
    if owner[node]>=0 or node in seen: continue
    queue=deque([node]); seen.add(node); group=[]; boundary=set()
    while queue:
        at=queue.popleft(); group.append(at)
        for nxt in adj[at]:
            if owner[nxt]>=0: boundary.add(owner[nxt])
            elif nxt not in seen: seen.add(nxt); queue.append(nxt)
    if len(boundary)==1:
        for at in group: owner[at]=next(iter(boundary))
depth=[-1]*len(nodes)
for section,start in enumerate(starts):
    depth[start]=0; queue=deque([start])
    while queue:
        at=queue.popleft()
        for nxt in adj[at]:
            if owner[nxt]==section and depth[nxt]<0:
                depth[nxt]=depth[at]+1; queue.append(nxt)
sites=[dict(x=n['x'],y=n['y'],section=s,depth=d) for n,s,d in zip(nodes,owner,depth)]
metadata=dict(starts=starts,sites=sites,edges=edges)
(source/'sections.json').write_text(json.dumps(metadata,indent=2))
def packed(items, per=4):
    return '\n'.join('    '+','.join(items[i:i+per])+',' for i in range(0,len(items),per))
header='''// Standard dat02 layout: Grayfox96/FFX-Sphere-Grid-viewer (MIT),\n// generated by Docs/Scripts/Offline/generate_sphere_sections.py.\n// Source URLs/hashes/license retained with sphere_sections_20261005_145728_598168.\n// Starts verified in native A53DE0, static table 00C86C10. No save/game reads.\n#pragma once\n#include <array>\nnamespace ffx {\nstruct SphereSectionSite { short x,y,section,depth; };\nstruct SphereSectionEdge { unsigned short a,b; };\n'''
header+='inline constexpr std::array<int,7> sphereSectionStarts={'+','.join(map(str,starts))+'};\n'
header+='inline constexpr std::array<SphereSectionSite,860> sphereSectionSites={{\n'
header+=packed(['{'+','.join(map(str,s.values()))+'}' for s in sites])+'\n}};\n'
header+='inline constexpr std::array<SphereSectionEdge,881> sphereSectionEdges={{\n'
header+=packed(['{'+','.join(map(str,e))+'}' for e in edges])+'\n}};\n}\n'
assert len(header.splitlines())<500
(root/'src/native/sphere_sections_data.hpp').write_text(header)
print('Standard sections:',dict(Counter(owner)),'starts:',starts,'header lines:',len(header.splitlines()))
expert=Path(__file__).parent/'output/sphere_sections_20261005_151825_382529'
def read_rows(filename):
    return [bytes(int(x,16) for x in line.split(',')) for line in (expert/filename).read_text().splitlines()]
expert_nodes=read_rows('nodes_dat03.csv'); expert_types=read_rows('dat11.csv')
expert_edges=[struct.unpack_from('<2H',r) for r in read_rows('links_dat03.csv')]
expert_starts=list(struct.unpack_from('<7H',raw,0xc86c20-0xc0a000))
sites=[dict(x=struct.unpack_from('<h',r)[0],y=struct.unpack_from('<h',r,2)[0],present=int(t[0]!=255)) for r,t in zip(expert_nodes,expert_types)]
header='''// Expert dat03 layout: Grayfox96/FFX-Sphere-Grid-viewer (MIT).\n// Generated from preserved data/URLs/hashes/license by generate_sphere_sections.py.\n// Native A53DE0's 00C86C20 start table anchors generic paths, not character sections.\n#pragma once\n#include <array>\n#include "sphere_sections_data.hpp"\nnamespace ffx {\nstruct SphereExpertSite { short x,y; bool present; };\n'''
header+='inline constexpr std::array<int,7> sphereExpertStarts={'+','.join(map(str,expert_starts))+'};\n'
header+='inline constexpr std::array<SphereExpertSite,828> sphereExpertSites={{\n'+packed(['{'+','.join(map(str,s.values()))+'}' for s in sites])+'\n}};\n'
header+='inline constexpr std::array<SphereSectionEdge,834> sphereExpertEdges={{\n'+packed(['{'+','.join(map(str,e))+'}' for e in expert_edges])+'\n}};\n}\n'
assert len(sites)==828 and len(expert_edges)==834 and len(header.splitlines())<500
(root/'src/native/sphere_expert_data.hpp').write_text(header)
(expert/'sections.json').write_text(json.dumps(dict(starts=expert_starts,sites=sites,edges=expert_edges),indent=2))
print('Expert nodes:',len(sites),'present:',sum(s['present'] for s in sites),'links:',len(expert_edges))
