"""Test-only original Winno constant/entry/jump/call tables, never a game read."""
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parents[3]
lines = ['// Original archived tables; generated by generate_jecht_round_fixture.py.',
         '#pragma once', 'struct RoundCall {unsigned id,count;};',
         'struct RoundWorker {unsigned variant,local;const unsigned *entries,*jumps;const int *ints;unsigned entryCount,jumpCount,intCount;};']
rows, calls, scores = [], {}, []
for variant, (name, main) in enumerate([('swin0000',32),('swin0200',24)]):
    data = json.loads((Path(sys.argv[1])/(name+'.json')).read_text())
    code=bytes.fromhex(data['script']['code'])
    guard=next(b for b in data['compiled']['workers'][main]['blocks'] if
               b['start']>=data['script']['workers'][main]['entries'][8 if variant==0 else 6] and
               any(s['kind']=='branch' and s['condition'].endswith(' > 10)') for s in b['statements']))
    pc=guard['start']
    if code[pc]!=0x9f or code[pc+3:pc+7]!=bytes.fromhex('ae0a000a'):
        raise ValueError('Original score>10 bytecode required')
    scores.append(int.from_bytes(code[pc+1:pc+3],'little'))
    for local in (main,main+1,main+2):
        w = data['script']['workers'][local]
        for key, type_name in [('entries','unsigned'),('jumps','unsigned'),('ints','int')]:
            values = w[key]
            lines.append(f'inline constexpr {type_name} round_{variant}_{local}_{key}[]={{'+(','.join(map(str,values)) if values else '0')+'};')
        rows.append('{%d,%d,round_%d_%d_entries,round_%d_%d_jumps,round_%d_%d_ints,%d,%d,%d}' %
                    (variant,local,variant,local,variant,local,variant,local,len(w['entries']),len(w['jumps']),len(w['ints'])))
        for b in data['compiled']['workers'][local]['blocks']:
            for s in b['statements']:
                if s['kind']=='call':
                    if not s['signature_known'] or not s['signature_agrees']:
                        raise ValueError(f'Unknown original call {s}')
                    count = len(s['args'])
                    if s['id'] in calls and calls[s['id']]!=count:raise ValueError('Inconsistent original arity')
                    calls[s['id']]=count
lines += ['inline constexpr unsigned roundScores[]={'+','.join(map(str,scores))+'};',
          'inline constexpr RoundWorker roundWorkers[]={'+','.join(rows)+'};',
          'inline constexpr RoundCall roundCalls[]={'+','.join('{%d,%d}'%pair for pair in sorted(calls.items()))+'};']
out=root/'src/native/tests/jecht_round_data.hpp'
out.write_text('\n'.join(lines)+'\n')
print(f'{len(rows)} archived workers; {len(calls)} original call arities; {out}')
