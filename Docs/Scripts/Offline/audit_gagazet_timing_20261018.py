# Game-source inputs/exports live outside every Git tree.
from pathlib import Path as _EvidencePath
import sys as _evidence_sys
_evidence_repo = next(p for p in _EvidencePath(__file__).resolve().parents
                      if (p / "Docs/Scripts/Offline/evidence_paths.py").is_file())
_evidence_sys.path.insert(0, str(_evidence_repo / "Docs/Scripts/Offline"))
from evidence_paths import evidence_path, evidence_relative, write_replay_adapter

from pathlib import Path
import hashlib,json,struct
root=Path(__file__).resolve().parents[3]
flow_path=evidence_path(root/'Docs/Scripts/Offline/output/dylan_reports_20261018_011846/mtgz0700.json')
flow=json.loads(flow_path.read_text())
rows=[]
for worker in (5,7):
    w=flow['workers'][worker]
    for entry in (6,8,9):
        start=w['entries'][entry]
        end=min((p for p in w['entries'] if p>start),default=0x1800)
        elapsed=0;duration=None
        for b in w['blocks']:
            for s in b['statements']:
                if not start<=s['pc']<end:continue
                if s.get('id')==0x1d:duration=int(s['args'][1])
                if s.get('id')==0x1b:
                    assert duration is not None
                    rows.append((worker,entry,s['pc'],duration,elapsed))
                    elapsed+=duration;duration=None
        assert elapsed==({5:192,7:288}[worker]*{6:1,8:.25,9:2}[entry])
assert len(rows)==30
source=evidence_path(root/'Docs/Scripts/Offline/output/gagazet_cave_assets_20261016/files/ffx_ps2/ffx/master/jppc/event/obj/mt/mtgz0700/mtgz070000.mgrp')
data=source.read_bytes()
models=struct.unpack_from('<I',data,4)[0];table=struct.unpack_from('<I',data,12)[0]
model=next(struct.unpack_from('<5I',data,table+i*20) for i in range(models) if struct.unpack_from('<I',data,table+i*20+4)[0]==5)
motions={}
for i in range(model[2]&0xffff):
    mid,_,_,seq=struct.unpack_from('<4I',data,model[3]+i*16)
    if mid not in (332005,332006):continue
    assert data[seq]==1
    index=struct.unpack_from('<H',data,seq+1)[0]
    header=struct.unpack_from('<4I',data,model[4]+index*16)
    frames=struct.unpack_from('<2H',data,header[2])
    assert frames[0]==0
    motions[str(mid)]=dict(index=index,frames=frames[1],header=header)
assert [motions[str(mid)]['frames'] for mid in (332005,332006)]==[36,19]
out=evidence_path(root/'Docs/Scripts/Offline/output/gagazet_timing_20261018');out.mkdir(exist_ok=True)
(out/'proof.json').write_text(json.dumps(dict(flow_sha256=hashlib.sha256(flow_path.read_bytes()).hexdigest(),
    motion_source=str(evidence_relative(source, root)),motion_sha256=hashlib.sha256(data).hexdigest(),motions=motions,
    schedules=rows,nominal_animation_frames=55,
    semantics='Confirm waits for first34 frames of332005, then its remaining2 and all19 frames of332006. Native waits15/10 overlap those animations. Production measures the full native rotation-clock delay including request scheduling on a manual throw; it never guesses55 as the cue lead.',
    gaps='Fixture supplies native-ready poses/timers. Actual audible reaction timing and runtime frame/animation order require gameplay confirmation.'),indent=2)+'\n')
header=['// Original mtgz0700 schedules; generated by audit_gagazet_timing_20261018.py.',
    'struct GagazetRingStage {unsigned worker,entry,pc,duration,start;};',
    'inline constexpr GagazetRingStage gagazetRingStages[]={']
header += ['{%u,%u,0x%x,%u,%u},'%r for r in rows]
header += ['};']
(root/'src/native/tests/gagazet_timing_data.inc').write_text('\n'.join(header)+'\n')
print('PASS:30 original ring stages; retained36/19-frame throw motions,55 nominal frames; live calibration includes native scheduling.')
